"""Offline regressions for the shared agent tooling checker."""

from __future__ import annotations

import os
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import agent_tooling as tooling

ROLE = tooling.Role(
    name="reviewer", description="Review a bounded change.", read_only=True
)
TARGETS = tooling.Targets(
    roles=frozenset({"reviewer"}),
    skills=frozenset({"chess"}),
    recipes=frozenset({"check", "sync-agents"}),
)


class FrontmatterTest(unittest.TestCase):
    def test_parses_scalars_quoted_strings_booleans_and_lists(self) -> None:
        parsed = tooling.parse_frontmatter(
            'name: qa\ndescription: "Checks: things."\nread-only: false\nskills:\n  - chess\n'
        )
        self.assertEqual(
            parsed,
            {
                "name": "qa",
                "description": "Checks: things.",
                "read-only": False,
                "skills": ["chess"],
            },
        )

    def test_rejects_unsupported_or_duplicate_keys(self) -> None:
        with self.assertRaises(ValueError):
            tooling.parse_frontmatter("metadata:\n  owner: hardware\n")
        with self.assertRaises(ValueError):
            tooling.parse_frontmatter("name: a\nname: b\n")

    def test_splits_frontmatter_from_body(self) -> None:
        self.assertEqual(
            tooling.split_frontmatter("---\nname: x\n---\nBody\n"),
            ("name: x", "Body\n"),
        )
        self.assertIsNone(tooling.split_frontmatter("No frontmatter"))


class SharedSourceTest(unittest.TestCase):
    def test_validates_the_skill_core(self) -> None:
        self.assertEqual(
            tooling.check_skill("s", "chess", {"name": "chess", "description": "x"}), []
        )
        self.assertEqual(len(tooling.check_skill("s", "chess", {"name": "other"})), 2)
        self.assertEqual(
            len(tooling.check_skill("s", "Bad", {"name": "Bad", "description": "x"})), 1
        )
        long = {"name": "chess", "description": "x" * 1025}
        self.assertEqual(len(tooling.check_skill("s", "chess", long)), 1)

    def test_validates_roles_without_a_fixed_roster(self) -> None:
        good = {"name": "new-role", "description": "Inspect source.", "read-only": True}
        self.assertEqual(
            tooling.check_role("r", "new-role", good, "Body", TARGETS.skills), []
        )
        bad = {**good, "name": "new-role", "read-only": "yes", "skills": ["missing"]}
        self.assertEqual(
            [
                f.message
                for f in tooling.check_role("r", "new-role", bad, " ", TARGETS.skills)
            ],
            [
                "read-only must be true or false",
                "skills: no .agents/skills/missing/SKILL.md",
                "the role body is empty",
            ],
        )


class AdapterTest(unittest.TestCase):
    def test_renders_native_wrappers_that_point_at_the_shared_role(self) -> None:
        claude = tooling.render_claude_agent(
            tooling.Role(
                "developer", 'Builds "slices".', read_only=False, skills=("chess",)
            )
        )
        self.assertIn('description: "Builds \\"slices\\"."', claude)
        self.assertIn("disallowedTools: Agent\nskills:\n  - chess\n---", claude)
        self.assertIn(".agents/roles/developer.md", claude)
        self.assertIn(
            "Edit, Write, NotebookEdit, Agent", tooling.render_claude_agent(ROLE)
        )
        codex = tooling.render_codex_agent(ROLE)
        self.assertTrue(codex.startswith("# Generated by just sync-agents"))
        self.assertIn('name = "reviewer"', codex)

    def test_sync_creates_links_and_wrappers_then_reports_no_drift(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            (root / "AGENTS.md").write_text("# Agents\n")
            (root / ".agents/skills/chess").mkdir(parents=True)
            drift = tooling.sync_adapters(root, [ROLE], ["chess"], write=False)
            self.assertEqual(len(drift), 6)
            self.assertEqual(
                tooling.sync_adapters(root, [ROLE], ["chess"], write=True), []
            )
            self.assertEqual(
                tooling.sync_adapters(root, [ROLE], ["chess"], write=False), []
            )
            self.assertEqual(os.readlink(root / "CLAUDE.md"), "AGENTS.md")
            self.assertEqual(
                os.readlink(root / ".github/copilot-instructions.md"),
                os.path.join("..", "AGENTS.md"),
            )
            self.assertEqual(
                os.readlink(root / ".claude/skills/chess"), "../../.agents/skills/chess"
            )

    def test_regenerates_owned_drift_but_refuses_local_copies(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            (root / "AGENTS.md").write_text("# Agents\n")
            tooling.sync_adapters(root, [ROLE], [], write=True)
            wrapper = root / ".claude/agents/reviewer.md"
            wrapper.write_text(wrapper.read_text() + "edited\n")
            self.assertEqual(
                len(tooling.sync_adapters(root, [ROLE], [], write=False)), 1
            )
            tooling.sync_adapters(root, [ROLE], [], write=True)
            self.assertEqual(wrapper.read_text(), tooling.render_claude_agent(ROLE))

            (root / "CLAUDE.md").unlink()
            (root / "CLAUDE.md").write_text("local copy\n")
            findings = tooling.sync_adapters(root, [ROLE], [], write=True)
            self.assertEqual([f.file for f in findings], ["CLAUDE.md"])
            self.assertEqual((root / "CLAUDE.md").read_text(), "local copy\n")


class ReferenceTest(unittest.TestCase):
    def test_reads_links_from_prose_only(self) -> None:
        markdown = (
            "[a](docs/a.md#x) [b](https://x.y) `[c](code.md)`\n```\n[d](d.md)\n```\n"
        )
        self.assertEqual(tooling.relative_links(markdown), ["docs/a.md"])

    def test_finds_recipes_and_aliases(self) -> None:
        justfile = "set shell := ['bash']\ncheck: lint\n@quiet arg:\nalias c := check\nx := '1'\n"
        self.assertEqual(tooling.just_recipes(justfile), {"check", "quiet", "c"})

    def test_reports_unknown_recipes_skills_and_roles(self) -> None:
        markdown = (
            "Run `just check`, `just missing` and `just --justfile <pkg>/justfile check`.\n"
            "Load the `chess` skill and the `ghost` skill; ask role `reviewer` and role `lead`.\n"
        )
        messages = [
            f.message
            for f in tooling.dangling_references(
                Path("/"), "AGENTS.md", markdown, TARGETS
            )
        ]
        self.assertEqual(
            messages,
            [
                "just missing: no such justfile recipe",
                "skill ghost: no .agents/skills/ghost/SKILL.md",
                "role lead: no .agents/roles/lead.md",
            ],
        )

    def test_checks_recipes_in_named_package_justfiles(self) -> None:
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            (root / "crates/chess").mkdir(parents=True)
            (root / "crates/chess/justfile").write_text("check:\n    true\n")
            markdown = "`just --justfile crates/chess/justfile check` `just --justfile crates/chess/justfile nope`"
            self.assertEqual(
                [
                    f.message
                    for f in tooling.dangling_references(root, "f", markdown, TARGETS)
                ],
                ["just --justfile crates/chess/justfile nope: no such recipe"],
            )

    def test_only_treats_rooted_backticked_paths_as_paths(self) -> None:
        markdown = "`crates/chess` `apps/<name>` `_generated/x` `docs/` `just check`"
        self.assertEqual(
            tooling.repo_path_mentions(markdown, {"crates", "docs"}),
            ["crates/chess", "docs/"],
        )


class ConfigTest(unittest.TestCase):
    def test_settings_plugins_need_a_known_marketplace(self) -> None:
        self.assertEqual(tooling.check_settings("s", {"attribution": {}}), [])
        messages = [
            f.message
            for f in tooling.check_settings(
                "s",
                {
                    "enabledPlugins": {
                        "a": True,
                        "b@x": True,
                        "c@claude-plugins-official": "y",
                    }
                },
            )
        ]
        self.assertEqual(
            messages,
            [
                "a must be named plugin@marketplace",
                "b@x needs x in extraKnownMarketplaces",
                "enabledPlugins.c@claude-plugins-official must be true or false",
            ],
        )

    def test_mcp_servers_need_a_command_or_url(self) -> None:
        self.assertEqual(
            tooling.check_mcp_config("m", {"mcpServers": {"a": {"url": "x"}}}), []
        )
        self.assertEqual(
            len(tooling.check_mcp_config("m", {"mcpServers": {"a": {"args": [1]}}})), 2
        )
        self.assertEqual(len(tooling.check_mcp_config("m", [])), 1)


